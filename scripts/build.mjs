import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = ['annotation.js', 'runtime.js', 'client.js'].map(name =>
  fs.readFileSync(path.join(root, 'src', name), 'utf8').replace(/^import .*;\n/gm, '').replace(/^export /gm, '')).join('\n');
const output = `// Generated by scripts/build.mjs. Commit this file so installs need no build scripts.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-browser-annotation',\n  factory(require) {\n${source}\n    return plugin(require('react'));\n  }\n});\n`;
const target = path.join(root, 'client.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) throw Error('client.js is stale; run npm run build');
} else fs.writeFileSync(target, output);
